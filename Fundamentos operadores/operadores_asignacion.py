# Operadores de comparación
#variable x
x = 5


#Suma
x=x+2
x+=2
print(f"Suma: {x}")
x = 5

#Resta
x=x-2
x-=2
print(f"Resta: {x}")
x = 5

#Multiplicación
x=x*2
x*=2
print(f"Multiplicación: {x}")
x = 5

#División
x=x/2
x/=2
print(f"División: {x}")
x = 5

#División entera
x=x//2
x//=2
print(f"División entera: {x}")
x = 5

#Residuo
x=x%2
x%=2
print(f"Residuo: {x}")
x = 5

#Potencia
x=x**2
x**=2
print(f"Potencia: {x}")    

#Walrus operator
print(f"El valor de x es: {(x := 5)}")#Asigna el valor de 5 a x y luego lo imprime


