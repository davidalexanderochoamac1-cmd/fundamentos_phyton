# Operadores de comparación

print("Verdaderos")

igual = 5 == 5
print(f"¿5 es igual a 5? {igual}")
diferente = 5 != 10
print(f"¿5 es diferente de 10? {diferente}") 
mayor = 5 > 4
print(f"¿5 es mayor que 10? {mayor}")
menor = 5 < 10
print(f"¿5 es menor que 4? {menor}")
mayor_igual = 5 >= 4
print(f"¿5 es mayor o igual a 10? {mayor_igual}")
menor_igual = 5 <= 10
print(f"¿5 es menor o igual a 4? {menor_igual}")

