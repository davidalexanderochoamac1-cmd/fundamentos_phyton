#Operadores

#Operadores aritméticos
a = 10
b = 5
suma = a + b
resta = a - b
multiplicacion = a * b
division = a / b
division_entera = a // b
residuo = a % b
potencia = a ** b
# Imprime los resultados de las operaciones
print("Suma:", suma)
print("Resta:", resta)
print("Multiplicación:", multiplicacion)
print("División:", division)
print("División entera:", division_entera)
print("Residuo:", residuo)
print("Potencia:", potencia)

# Operadores de comparación
c = 10
d = 5
igual = c == d
diferente = c != d
mayor = c > d
menor = c < d
mayor_igual = c >= d
menor_igual = c <= d

# Imprime los resultados de las operaciones de comparación
print("Igual:", igual)
print("Diferente:", diferente)
print("Mayor:", mayor)
print("Menor:", menor)
print("Mayor o igual:", mayor_igual)
print("Menor o igual:", menor_igual)