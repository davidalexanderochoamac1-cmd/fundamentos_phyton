# ===================== VARIABLES =====================
# Aquí estamos creando variables con diferentes tipos de datos

nombre = "David"          # Tipo string (texto)
apellido = "Ochoa"       # Tipo string (texto)
edad = 18                # Tipo entero (int)
altura = 1.74            # Tipo decimal (float)
activo = True            # Tipo booleano (True o False)
correo = "flsmdfrb@gmail.com"  # Tipo string
telefono = "3128639385" # Tipo string (se usa string para no perder ceros o formato)
cedula = 1234567890      # Tipo entero (int)
ficha = "3321349"        # Tipo string
programa = "ADSO"        # Tipo string


# ===================== IMPRESIÓN =====================
# type() sirve para mostrar el tipo de dato de la variable
# print() muestra en pantalla el resultado

print(type(nombre), nombre)       # Muestra: tipo y valor de nombre
print(type(apellido), apellido)   # Muestra: tipo y valor de apellido
print(type(edad), edad)           # Muestra: tipo y valor de edad
print(type(altura), altura)       # Muestra: tipo y valor de altura
print(type(activo), activo)       # Muestra: tipo y valor de activo
print(type(correo), correo)       # Muestra: tipo y valor de correo
print(type(telefono), telefono)   # Muestra: tipo y valor de telefono
print(type(cedula), cedula)       # Muestra: tipo y valor de cedula
print(type(ficha), ficha)         # Muestra: tipo y valor de ficha
print(type(programa), programa)   # Muestra: tipo y valor de programa